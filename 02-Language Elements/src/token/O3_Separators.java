/**
 * Separadores utilizados en el ejemplo
 * <p>
 * - `{ }` → Delimitan el cuerpo del método `main` y la lista de elementos del array
 * - `( )` → Delimitan los parámetros de `main` y `println`
 * - `[ ]` → Declaran y acceden al array
 * - `;` → Finalizan las instrucciones
 * - `,` → Separa los elementos del array
 * - `.` → Accede `println`
 */


